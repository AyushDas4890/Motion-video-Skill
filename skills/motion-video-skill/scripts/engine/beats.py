"""Master beat sheet -> timeline. Each beat = one shot. Cuts land on spoken-word onsets (see docs/caps_listing.txt).
Run from work/:  python beats.py  -> beats.json, beats.js (BEATS + FILM_END), ../docs/beat_sheet.md, rhythm/device stats.

beats_data.py holds B = [(t0, lay, scene, visual, motif, sound, extra), ...] and END (film length; default PROJECT.filmEnd).
  t1 = the next beat's t0.  lay: S speaker full (kinetic chest caption) | X split (art + speaker, seam word) |
  C cutaway (art full frame, one boxed word low) | F full graphic (cards, text pages, titles; scene draws its own text).
  scene: a SCENES name from acts/*.js (None for plain S). A scene that does not exist yet renders a storyboard board.
  extra (all optional): zoom (S/X speaker zoom; S 1.16 settle, 1.32 punch-in), key (force the chest key word), cap
  ('none'|'word'|'seam'|'chest'|'chesttop'), tr ('cut' default | 'bloom' | 'drop' | 'whip'), bp ([x,y] transition origin),
  cam ('own' or {z0,z1,d,second,push,cut:[t,mult]}), fy/fs (X: which scene y lands mid-panel, scale), fx, anchor,
  szoom, pop, blur, mb, args (dict passed to the scene as c.a), nosplit.
"""
import json, statistics, os
import projcfg
from beats_data import B, END

P = projcfg.load()
FOOT_END = float(P.get('footage', {}).get('dur') or END)


def build():
    shots = []
    for i, b in enumerate(B):
        t0, lay, scene, vis, motif, snd, ex = b
        t1 = B[i + 1][0] if i + 1 < len(B) else END
        assert t1 > t0, f'beat {i+1} at {t0}: next beat must start later (got {t1})'
        assert lay in ('S', 'X', 'C', 'F'), f'beat {i+1}: layout {lay!r} must be S/X/C/F'
        d = dict(id=f'b{i+1:03d}', t0=t0, t1=t1, lay=lay, scene=scene, visual=vis, motif=motif, sound=snd)
        d.update({k: v for k, v in ex.items()})
        shots.append(d)
    return shots


if __name__ == '__main__':
    S = build()
    json.dump(S, open('beats.json', 'w', encoding='utf-8'), indent=1, ensure_ascii=False)
    open('beats.js', 'w', encoding='utf-8').write('const BEATS=' + json.dumps(S, ensure_ascii=False) + ';const FILM_END=' + str(END) + ';')
    d = [s['t1'] - s['t0'] for s in S]
    film = [x for s, x in zip(S, d) if s['t0'] < FOOT_END - 0.01] or d
    print(f'shots {len(S)}  mean {statistics.mean(film):.2f}s  median {statistics.median(film):.2f}s  min {min(film):.2f}  max {max(film):.2f}  film end {END}')
    print('  >3.4 s:', [(s['id'], s['t0'], round(x, 2)) for s, x in zip(S, d) if x > 3.4])
    print('  <2s share: %.0f%%  std %.2f  <1s %d  >2.5s %d' % (100 * sum(1 for x in film if x < 2) / len(film), statistics.pstdev(film), sum(x < 1 for x in film), sum(x > 2.5 for x in film)))
    by = {}
    for s, x in zip(S, d):
        if s['t0'] >= FOOT_END: continue
        k = {'S': 'speaker', 'X': 'split', 'C': 'cutaway', 'F': 'card/graphic'}[s['lay']]
        by[k] = by.get(k, 0) + min(x, FOOT_END - s['t0'])
    tot = sum(by.values()) or 1
    print('  device mix (time):', {k: f'{100*v/tot:.0f}%' for k, v in by.items()}, ' reference targets: cutaway 40-45, card 25-30, split 15-20, speaker 10-15')
    os.makedirs('../docs', exist_ok=True)
    caps = [w for c in json.load(open('caps.json', encoding='utf-8')) for w in c]
    with open('../docs/beat_sheet.md', 'w', encoding='utf-8') as f:
        f.write(f"# Beat sheet — {P.get('title', '')}\n\nOne row per shot. Cuts land on spoken-word onsets. Layouts: S speaker full (kinetic chest caption) · X split (seam word) · C full cutaway (one word low) · F full graphic (cards/text/title, no layout caption). Generated by `python beats.py` from `work/beats_data.py`.\n\n")
        f.write('| id | t0 | t1 | dur | layout | scene | words | visual | motif | sound |\n|---|---|---|---|---|---|---|---|---|---|\n')
        for s in S:
            ws = ' '.join(w[2] for w in caps if s['t0'] - 0.01 <= w[0] < s['t1'] - 0.01)
            f.write(f"| {s['id']} | {s['t0']:.2f} | {s['t1']:.2f} | {s['t1']-s['t0']:.2f} | {s['lay']} | {s['scene'] or '-'} | {ws} | {s['visual']} | {s['motif']} | {s['sound']} |\n")
